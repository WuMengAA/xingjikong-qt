#pragma once

#include <QString>

/** 退出守卫（2026-11-03 · 用户工作笔记序号 2「退出被控端要口令」）。
 *
 *  背景：教室机放在讲台上，学生/路过的老师随手就能「右键托盘 → 退出被控端」，
 *  一退出整台机器就不再受集控（课表不响、通知不来、远控断线），而且**现场没人
 *  会想到是"被退出了"** —— 这是最难排查的一类故障。所以给退出加一道口令。
 *
 *  口径（刻意从简）：
 *   · 口令在 QSettings `agent/quitPassword` 里，**空 = 不启用**（默认不打扰；
 *     没设口令的存量机器升级后行为不变，不会突然退不出去）。
 *   · 只挡「用户点退出」这一条路。系统关机/注销、任务管理器结束进程、OTA 自升级
 *     重启都**不受影响** —— 那些要么是管理员意志，要么是必须能自愈的路径；
 *     把它们也挡住只会让机器变成砖头。
 *   · 口令明文存 QSettings？否：存 **SHA-256(salt + 口令)**。教室机是学生能摸到的
 *     机器，明文口令等于把"再也不用别的班的口令"写在脸上。代价是忘记口令只能
 *     改注册表清键，可以接受（这是脱离手段，不是找回手段）。
 */
namespace QuitGuard {

/** 是否设置过口令（设置页据此显示"已启用/未启用"）。 */
bool hasPassword();

/** 设置/清除口令（空串 = 清除）。 */
void setPassword(const QString &plain);

/** 询问并校验；返回 true 表示可以退出。未设口令直接 true。
 *  口令错 → 弹一次提示并返回 false（不退出，界面照常运行）。 */
bool confirmQuit();

}   // namespace QuitGuard
